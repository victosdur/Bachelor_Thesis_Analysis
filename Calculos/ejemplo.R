x=c(10,30,40,20,7,3,200,4,50,70)
y=rep(1,length(x))
datos=data.frame(ingresos=x,individuo=y)
library(tidyverse)
library(dplyr)
datos = datos %>% arrange(ingresos)
porc=cumsum(y/length(y))
acumingresos=cumsum(datos$ingresos)
porcingresos=acumingresos/sum(datos$ingresos)
plot(porc,porcingresos,type="l",xlab="porcentaje poblacion",ylab="porcentaje ingresos",xlim=c(0,1))
abline(a=0,b=1)
library(reldist)
gini(x)
gini(datos$ingresos,datos$individuo)
